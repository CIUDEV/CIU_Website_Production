timetable[11] = november;
timetable[12] = december;

const outPath = join(__dirname, "../lib/prayerTimetableData.ts");
const body = `/** CIU published prayer calendar — auto-generated, do not edit by hand. */
export type TimetableDay = {
  fajr: string;
  zuhr: string;
  asr: string;
  maghrib: string;
  isha: string;
};

/** month 1–12, day 1–31 */
export const PRAYER_TIMETABLE: Record<number, TimetableDay[]> = ${JSON.stringify(timetable, null, 2)};

export function getTimetableDay(month: number, day: number): TimetableDay | null {
  const monthDays = PRAYER_TIMETABLE[month];
  if (!monthDays || day < 1 || day > monthDays.length) return null;
  return monthDays[day - 1] ?? null;
}
`;

writeFileSync(outPath, body);
console.log(`Wrote ${outPath}`);
