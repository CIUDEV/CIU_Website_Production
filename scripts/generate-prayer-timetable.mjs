function parseTime(time) {
  const [h, m] = time.split(":").map(Number);
  return { h, m };
}

function formatTime({ h, m }) {
  return `${h}:${String(m).padStart(2, "0")}`;
}

function lerpTime(a, b, t) {
  const am = a.h * 60 + a.m;
  const bm = b.h * 60 + b.m;
  const cm = Math.round(am + (bm - am) * t);
  return { h: Math.floor(cm / 60), m: cm % 60 };
}

function interpolateMonth(anchors, daysInMonth) {
  const sorted = [...anchors].sort((x, y) => x.day - y.day);
  const days = [];

  for (let day = 1; day <= daysInMonth; day += 1) {
    let left = sorted[0];
    let right = sorted[sorted.length - 1];

    for (let i = 0; i < sorted.length - 1; i += 1) {
      if (day >= sorted[i].day && day <= sorted[i + 1].day) {
        left = sorted[i];
        right = sorted[i + 1];
        break;
      }
    }

    const t = right.day === left.day ? 0 : (day - left.day) / (right.day - left.day);
    days.push({
      fajr: formatTime(lerpTime(parseTime(left.fajr), parseTime(right.fajr), t)),
      zuhr: formatTime(lerpTime(parseTime(left.zuhr), parseTime(right.zuhr), t)),
      asr: formatTime(lerpTime(parseTime(left.asr), parseTime(right.asr), t)),
      maghrib: formatTime(lerpTime(parseTime(left.maghrib), parseTime(right.maghrib), t)),
      isha: formatTime(lerpTime(parseTime(left.isha), parseTime(right.isha), t)),
    });
  }

  return days;
}

